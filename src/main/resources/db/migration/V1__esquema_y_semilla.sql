-- Tablas del anexo del examen. Las identidades se generan siempre sin IDs manuales.
CREATE TABLE cliente (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  documento VARCHAR2(11) NOT NULL UNIQUE, nombres VARCHAR2(120) NOT NULL,
  telefono VARCHAR2(15));
CREATE TABLE servicio (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR2(7) NOT NULL UNIQUE, nombre VARCHAR2(80) NOT NULL,
  precio NUMBER(10,2) NOT NULL CHECK (precio > 0),
  duracion_min NUMBER(4) NOT NULL, activo NUMBER(1) DEFAULT 1 NOT NULL);
CREATE TABLE vehiculo (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  placa VARCHAR2(7) NOT NULL UNIQUE, marca VARCHAR2(40) NOT NULL,
  modelo VARCHAR2(40) NOT NULL, anio NUMBER(4) NOT NULL,
  cliente_id NUMBER NOT NULL REFERENCES cliente(id));
CREATE TABLE orden_servicio (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR2(9) NOT NULL UNIQUE, fecha TIMESTAMP NOT NULL,
  vehiculo_id NUMBER NOT NULL REFERENCES vehiculo(id),
  kilometraje NUMBER(7) NOT NULL, estado VARCHAR2(12) NOT NULL,
  total NUMBER(10,2) NOT NULL, usuario_registro VARCHAR2(30) NOT NULL,
  motivo_anulacion VARCHAR2(200));
CREATE TABLE detalle_orden (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_id NUMBER NOT NULL REFERENCES orden_servicio(id),
  servicio_id NUMBER NOT NULL REFERENCES servicio(id),
  cantidad NUMBER(2) NOT NULL, precio_unitario NUMBER(10,2) NOT NULL,
  subtotal NUMBER(10,2) NOT NULL);
-- El anexo remite a la sesion 10 para estas tres tablas.
CREATE TABLE usuarios (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR2(30) NOT NULL UNIQUE,
  password VARCHAR2(100) NOT NULL,
  nombre_completo VARCHAR2(120) NOT NULL,
  activo NUMBER(1) DEFAULT 1 NOT NULL);
CREATE TABLE roles (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR2(30) NOT NULL UNIQUE);
CREATE TABLE usuario_roles (
  usuario_id NUMBER NOT NULL REFERENCES usuarios(id),
  rol_id NUMBER NOT NULL REFERENCES roles(id),
  PRIMARY KEY (usuario_id, rol_id));
-- Un correlativo separado evita SELECT MAX + 1 y colisiones entre peticiones.
-- Los saltos tras rollback son normales en una secuencia Oracle.
CREATE SEQUENCE orden_numero_seq START WITH 5 INCREMENT BY 1 NOCYCLE NOCACHE;
CREATE INDEX ix_vehiculo_cliente ON vehiculo(cliente_id);
CREATE INDEX ix_orden_vehiculo_fecha ON orden_servicio(vehiculo_id, fecha);
CREATE INDEX ix_detalle_orden ON detalle_orden(orden_id);
CREATE INDEX ix_detalle_servicio ON detalle_orden(servicio_id);

